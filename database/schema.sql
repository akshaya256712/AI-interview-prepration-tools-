-- AI Interview Preparation Tools
-- Run this complete script in the Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  name varchar(80) not null check (char_length(trim(name)) >= 2),
  email varchar(254) not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  category varchar(30) not null check (category in ('HR','Technical','Behavioral','Career')),
  question text not null unique,
  tip text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.practice_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  question_id bigint not null references public.questions(id) on delete restrict,
  question_text text not null,
  category varchar(30) not null,
  answer text not null check (char_length(trim(answer)) between 10 and 10000),
  created_at timestamptz not null default now()
);

create index if not exists idx_practice_sessions_user_created
  on public.practice_sessions(user_id, created_at desc);
create index if not exists idx_questions_category_active
  on public.questions(category, is_active);

-- The Express backend uses the Supabase service-role key, which bypasses RLS.
-- All private session routes enforce ownership using the verified JWT user ID.
-- Do not expose the service-role key to browser code or commit it to Git.
alter table public.users enable row level security;
alter table public.questions enable row level security;
alter table public.practice_sessions enable row level security;
-- No browser-facing policies are created. Access is through the protected backend.

